#!/usr/bin/env python3
"""
Mermaid Diagram Generator for Zero Trust Architecture

Generates architecture diagrams from component definitions.
"""

import json
import yaml
from pathlib import Path
from typing import Dict, List, Any, Optional
from dataclasses import dataclass, asdict
from enum import Enum

def _label(text) -> str:
    """Quote a Mermaid node label; embedded double quotes become the #quot; entity."""
    return '"' + str(text).replace('"', '#quot;') + '"'

class ZoneType(Enum):
    INTERNET = "internet"
    EDGE = "edge"
    IDENTITY = "identity"
    DEVICE = "device"
    NETWORK = "network"
    PLATFORM = "platform"
    APPLICATION = "application"
    DATA = "data"
    VISIBILITY = "visibility"

@dataclass
class Component:
    id: str
    name: str
    zone: ZoneType
    type: str
    description: str = ""
    connections: List[str] = None
    metadata: Dict[str, Any] = None

@dataclass
class TrustZone:
    id: str
    name: str
    zone_type: ZoneType
    components: List[str]
    trust_assumptions: str = ""
    boundary_controls: str = ""

class MermaidGenerator:
    ZONE_COLORS = {
        ZoneType.INTERNET: "#ffebee",
        ZoneType.EDGE: "#fff3e0",
        ZoneType.IDENTITY: "#e8f5e9",
        ZoneType.DEVICE: "#e3f2fd",
        ZoneType.NETWORK: "#fce4ec",
        ZoneType.PLATFORM: "#f3e5f5",
        ZoneType.APPLICATION: "#fff8e1",
        ZoneType.DATA: "#e0f2f1",
        ZoneType.VISIBILITY: "#fafafa"
    }
    
    ZONE_LABELS = {
        ZoneType.INTERNET: "Internet / Untrusted",
        ZoneType.EDGE: "Edge / ZTNA",
        ZoneType.IDENTITY: "Identity Fabric",
        ZoneType.DEVICE: "Device Trust",
        ZoneType.NETWORK: "Network Segmentation",
        ZoneType.PLATFORM: "Platform / Workloads",
        ZoneType.APPLICATION: "Applications",
        ZoneType.DATA: "Data Protection",
        ZoneType.VISIBILITY: "Visibility & Analytics"
    }

    def __init__(self):
        self.components: Dict[str, Component] = {}
        self.zones: Dict[str, TrustZone] = {}

    def add_component(self, component: Component):
        self.components[component.id] = component

    def add_zone(self, zone: TrustZone):
        self.zones[zone.id] = zone

    def load_from_yaml(self, file_path: Path):
        """Load architecture from YAML file."""
        with open(file_path) as f:
            data = yaml.safe_load(f)
        
        for zone_data in data.get("zones", []):
            zone_type = ZoneType(zone_data["type"])
            zone = TrustZone(
                id=zone_data["id"],
                name=zone_data["name"],
                zone_type=zone_type,
                components=zone_data.get("components", []),
                trust_assumptions=zone_data.get("trust_assumptions", ""),
                boundary_controls=zone_data.get("boundary_controls", "")
            )
            self.add_zone(zone)
        
        for comp_data in data.get("components", []):
            component = Component(
                id=comp_data["id"],
                name=comp_data["name"],
                zone=ZoneType(comp_data["zone"]),
                type=comp_data["type"],
                description=comp_data.get("description", ""),
                connections=comp_data.get("connections", []),
                metadata=comp_data.get("metadata", {})
            )
            self.add_component(component)

    def generate_architecture_diagram(self, show_details: bool = False) -> str:
        """Generate Mermaid architecture diagram."""
        lines = [
            "graph TB",
            "    %% Zero Trust Architecture Diagram",
            "    %% Generated by zero-trust-architecture skill",
            ""
        ]
        
        # Define zones as subgraphs
        for zone in self.zones.values():
            color = self.ZONE_COLORS.get(zone.zone_type, "#ffffff")
            label = self.ZONE_LABELS.get(zone.zone_type, zone.name)
            lines.append(f"    subgraph {zone.id}[\"{label}\"]")
            lines.append(f"        direction TB")
            lines.append(f"        style {zone.id} fill:{color},stroke:#333,stroke-width:2px")
            
            # Add components in this zone
            for comp_id in zone.components:
                if comp_id in self.components:
                    comp = self.components[comp_id]
                    node_id = comp.id.replace("-", "_").replace(".", "_")
                    # Use different shapes for different types
                    if comp.type in ["gateway", "proxy", "pep"]:
                        lines.append(f"        {node_id}[[{_label(comp.name)}]]")
                    elif comp.type in ["database", "store"]:
                        lines.append(f"        {node_id}[({_label(comp.name)})]")
                    elif comp.type in ["identity", "idp", "pam"]:
                        lines.append(f"        {node_id}(({_label(comp.name)}))")
                    else:
                        lines.append(f"        {node_id}[{_label(comp.name)}]")
                    
                    if show_details and comp.description:
                        lines.append(f"        {node_id} -.->|{_label(comp.description)}| {node_id}_desc")
                        lines.append(f"        {node_id}_desc[/{_label(comp.description)}/]")
            
            lines.append("    end")
            lines.append("")
        
        # Add connections
        lines.append("    %% Connections")
        for comp in self.components.values():
            if comp.connections:
                node_id = comp.id.replace("-", "_").replace(".", "_")
                for target_id in comp.connections:
                    target_node = target_id.replace("-", "_").replace(".", "_")
                    lines.append(f"    {node_id} --> {target_node}")
        
        # Add cross-zone trust boundaries
        lines.append("")
        lines.append("    %% Trust Zone Boundaries")
        lines.append("    classDef internet fill:#ffebee,stroke:#c62828,stroke-width:2px;")
        lines.append("    classDef edge fill:#fff3e0,stroke:#e65100,stroke-width:2px;")
        lines.append("    classDef identity fill:#e8f5e9,stroke:#2e7d32,stroke-width:2px;")
        lines.append("    classDef device fill:#e3f2fd,stroke:#1565c0,stroke-width:2px;")
        lines.append("    classDef network fill:#fce4ec,stroke:#c2185b,stroke-width:2px;")
        lines.append("    classDef platform fill:#f3e5f5,stroke:#6a1b9a,stroke-width:2px;")
        lines.append("    classDef app fill:#fff8e1,stroke:#f57f17,stroke-width:2px;")
        lines.append("    classDef data fill:#e0f2f1,stroke:#00695c,stroke-width:2px;")
        lines.append("    classDef visibility fill:#fafafa,stroke:#616161,stroke-width:2px;")
        
        for zone in self.zones.values():
            class_name = zone.zone_type.value
            for comp_id in zone.components:
                if comp_id in self.components:
                    node_id = comp_id.replace("-", "_").replace(".", "_")
                    lines.append(f"    class {node_id} {class_name};")
        
        return "\n".join(lines)

    def generate_data_flow_diagram(self) -> str:
        """Generate data flow diagram showing user/request flows."""
        lines = [
            "graph LR",
            "    %% Zero Trust Data Flow Diagram",
            ""
        ]
        
        # Define the main flow
        lines.append("    User[👤 User]")
        lines.append("    Browser[🌐 Browser]")
        lines.append("    ZTNA[🔒 ZTNA Gateway]")
        lines.append("    IdP[🆔 Identity Provider]")
        lines.append("    Device[📱 Device Posture]")
        lines.append("    PE[🧠 Policy Engine]")
        lines.append("    PA[⚙️ Policy Admin]")
        lines.append("    Mesh[☸️ Service Mesh]")
        lines.append("    App[📦 Application]")
        lines.append("    Data[💾 Data Store]")
        lines.append("")
        
        # Main flow
        lines.append("    User --> Browser")
        lines.append("    Browser --> ZTNA")
        lines.append("    ZTNA --> IdP")
        lines.append("    ZTNA --> Device")
        lines.append("    IdP --> PE")
        lines.append("    Device --> PE")
        lines.append("    PE --> PA")
        lines.append("    PA --> ZTNA")
        lines.append("    ZTNA --> Mesh")
        lines.append("    Mesh --> App")
        lines.append("    App --> Data")
        lines.append("")
        
        # Control plane (dashed)
        lines.append("    %% Control Plane (decision flow)")
        lines.append("    ZTNA -.->|Request + Context| PE")
        lines.append("    PE -.->|Decision| PA")
        lines.append("    PA -.->|Configure| ZTNA")
        lines.append("")
        
        # Continuous verification
        lines.append("    %% Continuous Verification")
        lines.append("    Mesh -.->|Re-evaluate| PE")
        lines.append("    App -.->|Re-evaluate| PE")
        lines.append("")
        
        # Styling
        lines.append("    classDef user fill:#e3f2fd,stroke:#1565c0;")
        lines.append("    classDef enforcement fill:#fff3e0,stroke:#e65100;")
        lines.append("    classDef policy fill:#e8f5e9,stroke:#2e7d32;")
        lines.append("    classDef resource fill:#fce4ec,stroke:#c2185b;")
        lines.append("    classDef continuous fill:#f3e5f5,stroke:#6a1b9a,stroke-dasharray: 5 5;")
        
        lines.append("    class User,Browser user;")
        lines.append("    class ZTNA,Mesh enforcement;")
        lines.append("    class IdP,Device,PE,PA policy;")
        lines.append("    class App,Data resource;")
        
        return "\n".join(lines)

    def generate_trust_zone_matrix(self) -> str:
        """Generate trust zone matrix as Mermaid."""
        lines = [
            "graph TD",
            "    %% Trust Zone Matrix",
            ""
        ]
        
        zones_list = list(self.zones.values())
        for i, zone in enumerate(zones_list):
            lines.append(f"    {zone.id}[{_label(zone.name)}]")
            if zone.trust_assumptions:
                lines.append(f"    {zone.id}_assume[{_label(zone.trust_assumptions)}]")
                lines.append(f"    {zone.id} --> {zone.id}_assume")
            if zone.boundary_controls:
                lines.append(f"    {zone.id}_control[{_label(zone.boundary_controls)}]")
                lines.append(f"    {zone.id} --> {zone.id}_control")
        
        # Add cross-zone relationships
        lines.append("")
        lines.append("    %% Cross-Zone Trust Relationships")
        lines.append("    internet -->|Zero Trust| edge")
        lines.append("    edge -->|Verify Identity| identity")
        lines.append("    edge -->|Verify Device| device")
        lines.append("    identity -.->|Policy| network")
        lines.append("    device -.->|Policy| network")
        lines.append("    network -->|Enforce| platform")
        lines.append("    platform -->|Access| application")
        lines.append("    application -->|Protect| data")
        lines.append("    data -.->|Telemetry| visibility")
        lines.append("    platform -.->|Telemetry| visibility")
        lines.append("    network -.->|Telemetry| visibility")
        lines.append("    identity -.->|Telemetry| visibility")
        lines.append("")
        
        lines.append("    classDef untrusted fill:#ffebee,stroke:#c62828;")
        lines.append("    classDef enforcement fill:#fff3e0,stroke:#e65100;")
        lines.append("    classDef trusted fill:#e8f5e9,stroke:#2e7d32;")
        lines.append("    classDef resource fill:#fce4ec,stroke:#c2185b;")
        lines.append("    classDef monitor fill:#fafafa,stroke:#616161;")
        
        lines.append("    class internet untrusted;")
        lines.append("    class edge enforcement;")
        lines.append("    class identity,device trusted;")
        lines.append("    class network,platform,application trusted;")
        lines.append("    class data resource;")
        lines.append("    class visibility monitor;")
        
        return "\n".join(lines)

def main():
    import argparse
    parser = argparse.ArgumentParser(description="Generate Mermaid diagrams for Zero Trust Architecture")
    parser.add_argument("input", help="Input YAML file with architecture definition")
    parser.add_argument("--type", choices=["architecture", "dataflow", "matrix"], default="architecture",
                        help="Diagram type to generate")
    parser.add_argument("--output", "-o", help="Output file (default: stdout)")
    parser.add_argument("--details", action="store_true", help="Show component details")
    args = parser.parse_args()

    generator = MermaidGenerator()
    generator.load_from_yaml(Path(args.input))

    if args.type == "architecture":
        diagram = generator.generate_architecture_diagram(show_details=args.details)
    elif args.type == "dataflow":
        diagram = generator.generate_data_flow_diagram()
    elif args.type == "matrix":
        diagram = generator.generate_trust_zone_matrix()
    else:
        diagram = generator.generate_architecture_diagram()

    if args.output:
        with open(args.output, "w") as f:
            f.write(diagram)
        print(f"Diagram written to {args.output}")
    else:
        print(diagram)

if __name__ == "__main__":
    main()